#!/usr/bin/env node
/*********************************************************
 * Guard 10 — every `source_file` in the marketing seed must exist
 *
 * @description
 * The marketing site's catalogue (`packages/marketing/server/db/seed/*.json`
 * plus the `db-seed.sql` dump built from them) carries a `source_file` on
 * each entry: the repo-relative path of the file that declares the symbol.
 * That path is what the site turns into a "view source" link, and what any
 * later regeneration matches on to decide whether an entry is the same
 * symbol or a new one.
 *
 * @description
 * RULE: a `source_file` pointing at a path that does not exist in the
 * working tree is a broken link and a broken match key. There is no
 * legitimate reason for one, so the guard flags all of them.
 *
 * @description
 * WHY THIS GUARD EXISTS — the drift is silent, and it is not rare.
 * The seed is NOT regenerated by any build step or test. It is a committed
 * artefact. So the moment a declaration file is moved or renamed — which is
 * the entire substance of issue #368, and of every "one file per unit"
 * chantier after it — every entry pointing at the old path goes stale, and
 * nothing anywhere says so. Measured on the #368 merge: 8 dead paths before,
 * 84 after. Seventy-six links broke in one merge, and the full unit suite,
 * the type-check and the other nine guards were all green over it.
 *
 * @description
 * The failure is worse than a dead link. Because `source_file` is part of
 * how a regeneration recognises an existing entry, a stale path makes the
 * symbol look NEW: the next sync inserts a duplicate instead of updating,
 * and the old row stays behind as an orphan. That is why this is checked
 * rather than left to a doc-lint pass.
 *
 * @description
 * SCOPE. Only `source_file` values starting with `packages/` are checked —
 * those are repo-relative by construction. Anything else (absolute paths,
 * URLs, nulls) is left alone deliberately: the guard has no way to resolve
 * them and guessing would produce noise.
 *
 * @description
 * The `.sql` dump is checked too, not just the JSON. It is generated from
 * the JSON but committed separately, so the two can and did drift apart.
 * Checking only the source would let a stale dump ship.
 ********************************************************/

import { existsSync, readdirSync, readFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { report } from './lib/baseline.mjs'

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '../../../..')
const BASELINE = resolve(REPO, 'packages/ds/scripts/guards/baseline/seed-source-paths.json')

const SEED_DIR = 'packages/marketing/server/db/seed'
const SQL_DUMP = 'packages/marketing/server/assets/db-seed.sql'

/*********************************************************
 * collectFromJson
 *
 * @description
 * Walks an arbitrarily nested parsed JSON value and yields every path field
 * it carries. The seed's shape has changed more than once; walking
 * generically rather than assuming `{ rows: [...] }` is what keeps the guard
 * working across those changes.
 *
 * @description
 * BOTH spellings are collected, and that is not defensive padding: the seed
 * genuinely uses two. Top-level entries carry `source_file` (snake_case, the
 * DB column), while the token blocks nested inside a component entry carry
 * `sourceFile` (camelCase, a JSON payload field). Reading only the first
 * missed a real dead reference — the Media family's token doc points at
 * `tokens/component/media.json`, a file that has never existed, the real
 * ones being `media-controller.json` and `media-scrubber.json`.
 ********************************************************/
const PATH_FIELDS = ['source_file', 'sourceFile']

/*********************************************************
 * PATH_SHAPED
 *
 * @description
 * A path field does not always hold a path. `component.json` carries one
 * deliberate sentinel — `packages/ds/tokens/component/(no dedicated token
 * file)` — which is prose telling the site there is nothing to link to for
 * that family. Flagging it would be a false positive on intentional data.
 * @description
 * Rejecting anything with a space or a parenthesis is enough to separate
 * the two, and it stays honest: a real path never contains either in this
 * repo. Verified exhaustively — that sentinel is the only non-path value in
 * either field across the whole seed.
 ********************************************************/
const PATH_SHAPED = /^[A-Za-z0-9._/-]+$/

function collectFromJson (node, out) {
    if (Array.isArray(node)) {
        for (const child of node) collectFromJson(child, out)
        return
    }

    if (node && typeof node === 'object') {
        for (const field of PATH_FIELDS) {
            if (typeof node[field] === 'string') out.add(node[field])
        }

        for (const child of Object.values(node)) collectFromJson(child, out)
    }
}

/*********************************************************
 * collectFromSql
 *
 * @description
 * The dump is one large INSERT script, so the paths are string literals
 * rather than parsed fields. Matching on the `packages/…` shape directly is
 * deliberate: it needs no SQL parser and cannot be broken by a change in
 * column order or quoting style.
 *
 * @description
 * The trailing `(?![A-Za-z0-9])` is load-bearing and was not there at first:
 * without it, the `js` alternative matches the first two letters of a `.json`
 * path, so every `tokens/component/*.json` reference was reported as a dead
 * `*.js` file — 92 fabricated violations on the first run, all of them the
 * regex's own doing. An extension alternation always needs an end boundary
 * when one extension is a prefix of another.
 ********************************************************/
function collectFromSql (text, out) {
    for (const match of text.matchAll(/packages\/[A-Za-z0-9._/-]+\.(?:ts|tsx|vue|mjs|cjs|js|json|scss|css)(?![A-Za-z0-9])/g)) {
        out.add(match[0])
    }
}

const found = new Map()

const seedFiles = existsSync(resolve(REPO, SEED_DIR))
    ? readdirSync(resolve(REPO, SEED_DIR)).filter((f) => f.endsWith('.json')).map((f) => `${SEED_DIR}/${f}`)
    : []

for (const file of seedFiles) {
    const paths = new Set()

    collectFromJson(JSON.parse(readFileSync(resolve(REPO, file), 'utf8')), paths)

    for (const p of paths) {
        if (p.startsWith('packages/') && PATH_SHAPED.test(p) && !existsSync(resolve(REPO, p))) {
            if (!found.has(p)) found.set(p, new Set())

            found.get(p).add(file)
        }
    }
}

if (existsSync(resolve(REPO, SQL_DUMP))) {
    const paths = new Set()

    collectFromSql(readFileSync(resolve(REPO, SQL_DUMP), 'utf8'), paths)

    for (const p of paths) {
        if (!existsSync(resolve(REPO, p))) {
            if (!found.has(p)) found.set(p, new Set())

            found.get(p).add(SQL_DUMP)
        }
    }
}

const currentIds = [...found.keys()].sort()
const detailsById = new Map(
    currentIds.map((id) => [id, `cité par ${[...found.get(id)].sort().join(', ')}`])
)

process.exit(report({
    guardName: 'seed-source-paths (tout source_file du seed marketing doit exister)',
    baselinePath: BASELINE,
    currentIds,
    detailsById,
    fixHint: 'Un fichier a bougé sans que le seed suive. Réécrire les chemins depuis la table de renommage git :\n'
        + '  git log --diff-filter=R --name-status -M --format="" <base>..HEAD -- "packages/ds/src/*"\n'
        + 'puis appliquer chaque ancien→nouveau dans seed/*.json ET dans assets/db-seed.sql.'
}))
